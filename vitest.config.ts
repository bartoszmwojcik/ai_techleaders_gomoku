import { existsSync, readdirSync } from "node:fs";

import { defineConfig } from "vitest/config";

// shadcn/ui primitives are vendored from the shadcn registry (`npx shadcn add`), so they
// are excluded from the coverage threshold. Add every new shadcn component here; our own
// components and hooks in packages/ui stay fully covered.
const SHADCN_COMPONENTS = ["badge", "button", "card", "table"];

// One test project per workspace package, so new packages are picked up automatically.
const packages = readdirSync("packages", { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);

export default defineConfig({
  resolve: { tsconfigPaths: true },
  test: {
    projects: packages.map((name) => ({
      // Inherit the root options (resolve.tsconfigPaths, unstubEnvs, …).
      extends: true,
      test: {
        name,
        root: `packages/${name}`,
        include: ["src/**/*.test.{ts,tsx}", "*.test.ts"],
        environment: "node",
        // Optional per-package setup, e.g. stubbing `server-only` in packages/app.
        setupFiles: existsSync(`packages/${name}/vitest.setup.ts`) ? ["vitest.setup.ts"] : [],
      },
    })),
    // Tests stub process.env (`vi.stubEnv`) explicitly; restore it after every test so the
    // developer's environment (DATABASE_URL, NODE_ENV) never leaks between tests.
    unstubEnvs: true,
    coverage: {
      provider: "v8",
      include: ["packages/*/src/**/*.{ts,tsx}", "packages/app/next.config.ts"],
      exclude: [
        "**/*.test.{ts,tsx}",
        "**/*.d.ts",
        // Generated by the MikroORM CLI.
        "packages/db/src/migrations/**",
        ...SHADCN_COMPONENTS.map((name) => `packages/ui/src/components/${name}.tsx`),
      ],
      // Every file must be fully covered — see "Testy" in AGENTS.md.
      thresholds: { 100: true, perFile: true },
      reporter: ["text", "html", "json-summary"],
    },
  },
});
